#!/usr/bin/env python3
"""Writes tables.h, the curves fx.cpp reads: 33 points across a control and the
two saturation shapes. Run it after changing a curve here and commit both."""
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
RATE = 44100.0
BLOCK = 64
Q31 = 2147483647


def lerp_exp(low, high, t):
    return low * (high / low) ** t


def points(f):
    return [f(i / 32) for i in range(33)]


def q31(v):
    return max(-Q31, min(Q31, round(v * Q31)))


def pole(hz, rate=RATE):
    return 1 - math.exp(-2 * math.pi * hz / rate)


def allpass(hz):
    t = math.tan(math.pi * hz / RATE)
    return (t - 1) / (t + 1)


def semitones(t):
    """-12..12 across the control, flat for a sliver about the centre."""
    x = 2 * t - 1
    size = max(0.0, abs(x) - 0.03) / 0.97
    return math.copysign(12 * size ** 1.2, x)


def tube(x):
    """A warm stage: tanh, a little lopsided for even harmonics."""
    u = 2.2 * x + 0.35 * x * x
    return math.tanh(u) / math.tanh(2.55)


def fuzz(x):
    """A germanium pair: a dead spot about zero that bites as it's passed, and hard shoulders, the lower softer."""
    u = 3.0 * x
    u = math.copysign(max(0.0, abs(u) - 0.06), u)
    y = math.tanh(1.8 * u) if u > 0 else 0.82 * math.tanh(1.2 * u)
    return y


def row(name, kind, values, comment):
    return f"// {comment}\nconst {kind} {name}[{len(values)}] = {{{', '.join(str(v) for v in values)}}};\n"


TABLES = [
    ("kRateStep", "opxy::u32", points(lambda t: round(lerp_exp(0.08, 12, t) * BLOCK / RATE * 2 ** 32)), "An LFO's phase step per block, 2^32 a cycle: 0.08..12 Hz"),
    ("kPitchRatio", "opxy::i32", points(lambda t: round(2 ** (semitones(t) / 12) * 65536)), "Pitch: the ratio, Q16, -12..+12 semitones with a flat centre"),
    ("kSweep", "opxy::i32", points(lambda t: q31(allpass(lerp_exp(90, 5200, t)))), "The swirl's all-pass coefficient, Q31: its corner 90..5200 Hz"),
    ("kCutoff", "opxy::i32", points(lambda t: q31(min(0.98, 2 * math.sin(math.pi * lerp_exp(45, 16000, t) / RATE)))), "A state-variable filter's f, Q31: 45..16000 Hz"),
    ("kTwinDelay", "opxy::i32", points(lambda t: round(lerp_exp(9, 120, t) * RATE / 1000 * 256)), "Twin's delay, Q8 frames: 9..120 ms"),
    ("kFreeDelay", "opxy::i32", points(lambda t: round(lerp_exp(30, 1400, t) * RATE / 1000 * 256)), "A delay's time with no tempo, Q8 frames: 30..1400 ms"),
    ("kSliceFrames", "opxy::i32", points(lambda t: round(lerp_exp(18, 1300, t) * RATE / 1000)), "A slice's length, frames: 18..1300 ms"),
    ("kSwellRise", "opxy::i32", points(lambda t: q31(pole(1 / (2 * math.pi * lerp_exp(0.012, 0.6, t)), RATE / BLOCK))), "Swell: its rise a block, Q31: a time constant of 12 ms..0.6 s"),
    # Cloud: five characters run into each other over its control: chamber, room, hall, plate, cloud.
    ("kCloudSize", "opxy::i32", points(lambda t: round(lerp_exp(0.28, 1.6, t) * 65536)), "Cloud: the tank's size, Q16: 0.28..1.6"),
    ("kCloudDecay", "opxy::i32", points(lambda t: q31(0.52 + 0.465 * t ** 0.55)), "Cloud: the loop's decay, Q31: 0.52..0.985"),
    ("kCloudDamp", "opxy::i32", points(lambda t: q31(pole(lerp_exp(7000, 2600, t), RATE / 2))), "Cloud: the loop's low-pass, Q31: 7 kHz in a chamber to 2.6 kHz in a cloud"),
    ("kCloudWet", "opxy::i32", points(lambda t: q31(1.0 - 0.1 * t)), "Cloud: the wet's level, Q31, held near the dry's as the tank fills"),
]


def main():
    out = ["// Generated by tools/make_tables.py: the curves fx.cpp reads, at 33 points\n"
           "// across a control (0, 1/32 .. 1), interpolated between them.\n"
           "#pragma once\n#include <opxy/types.hpp>\n\nnamespace chroma {\n"]
    for name, kind, values, comment in TABLES:
        out.append(row(name, kind, values, comment))
    shape = lambda f: [q31(f(-1 + 2 * i / 128)) for i in range(129)]
    out.append(row("kTubeCurve", "opxy::i32", shape(tube), "The warm stage, Q31 across an input of -1..1"))
    out.append(row("kFuzzCurve", "opxy::i32", shape(fuzz), "The fuzz, Q31 across an input of -1..1"))
    out.append("}\n")
    (ROOT / "tables.h").write_text("".join(out))


if __name__ == "__main__":
    main()
