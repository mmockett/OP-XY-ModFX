#!/usr/bin/env python3
"""Writes tables.h: the curves fx.cpp reads instead of computing exponentials
on the OP-XY's fixed-point Blackfin. Run it after changing a range here and
commit both."""
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
RATE = 44100
POINTS = 33  # each curve at 0, 1/32 .. 1 of its control

ECHO_MS = (3.0, 650.0)          # the PT2399's range on the Dust Collector's panel
ECHO_DARK_HZ = (9000.0, 2200.0)  # its loop gets darker as the clock slows for long delays
LFO_HZ = (0.17, 7.5)             # LFO 1; LFO 2 runs 10/3 faster, as the hardware's 0.56..25 Hz
SWEEP_HZ = (100.0, 4000.0)       # the phaser's allpass corner: its notches sweep 41 Hz..9.7 kHz
DIODE_POINTS = 129               # each diode curve across its input, -1..1

# The Dust Collector's saturation: five diode pairs, one 1N4148 (silicon) and
# four 1N60 (germanium), from subtle (I) to squashed (V). Which pair each type
# switches in is not published; these are a soft-to-hard reading of it. Each is
# a series resistor into a diode pair: (forward diode, reverse diode, the
# voltage the control's full scale drives it with). A string of n diodes is
# one with n times its emission coefficient.
GERMANIUM = (0.5e-6, 1.3)   # 1N60: saturation current, emission coefficient
SILICON = (4e-9, 1.75)      # 1N4148
TYPES = (
    ('I', (GERMANIUM, 1), (GERMANIUM, 1), 0.3),
    ('II', (GERMANIUM, 1), (GERMANIUM, 1), 0.8),
    ('III', (GERMANIUM, 1), (GERMANIUM, 2), 1.6),   # one side two in series: even harmonics
    ('IV', (SILICON, 1), (SILICON, 1), 3.0),
    ('V', (SILICON, 1), (GERMANIUM, 1), 6.0),       # silicon against germanium: lopsided
)


def curve(low, high, i):
    return low * (high / low) ** (i / (POINTS - 1))


def onepole(hz):
    """Q31 coefficient of y += c * (x - y) for a corner at hz."""
    return round((1 - math.exp(-2 * math.pi * hz / RATE)) * 0x7fffffff)


def allpass(hz):
    t = math.tan(math.pi * hz / RATE)
    return round((t - 1) / (t + 1) * 0x7fffffff)


def clipper(forward, reverse, volts, u):
    """The diode pair's voltage for an input u (-1..1) through 1 kOhm: the
    current through the resistor equals the diodes'."""
    vt = 0.02585
    (fs, fn), fcount = forward
    (rs, rn), rcount = reverse
    current = lambda v: fs * (math.exp(min(v / (fn * fcount * vt), 80)) - 1) - rs * (math.exp(min(-v / (rn * rcount * vt), 80)) - 1)
    x = u * volts
    low, high = -abs(x) - 1, abs(x) + 1
    for _ in range(200):
        v = (low + high) / 2
        if (x - v) / 1000 - current(v) > 0:
            low = v
        else:
            high = v
    return (low + high) / 2


def diode_curves():
    """Each type's curve, scaled so its loudest point is 0.95 of full scale."""
    curves = []
    for _name, forward, reverse, volts in TYPES:
        points = [clipper(forward, reverse, volts, -1 + 2 * i / (DIODE_POINTS - 1)) for i in range(DIODE_POINTS)]
        peak = max(abs(v) for v in points)
        curves.append([round(v / peak * 0.95 * 0x7fffffff) for v in points])
    return curves


def table(name, kind, values, comment):
    body = ', '.join(str(v) for v in values)
    return f'// {comment}\nconst opxy::{kind} {name}[{len(values)}] = {{{body}}};\n'


def main():
    echo = [round(curve(*ECHO_MS, i) * RATE / 1000 * 256) for i in range(POINTS)]
    dark = [onepole(curve(*ECHO_DARK_HZ, i)) for i in range(POINTS)]
    lfo = [round(curve(*LFO_HZ, i) * 64 / RATE * 2 ** 32) for i in range(POINTS)]
    sweep = [allpass(curve(*SWEEP_HZ, i)) for i in range(POINTS)]
    curves = diode_curves()
    text = ('// Generated by tools/make_tables.py: the curves fx.cpp reads, at 33 points\n'
            '// across a control (0, 1/32 .. 1), interpolated between them.\n'
            '#pragma once\n#include <opxy/types.hpp>\n\nnamespace lint {\n'
            + table('kEchoDelay', 'i32', echo, f'Echo time, Q8 samples: {ECHO_MS[0]:g}..{ECHO_MS[1]:g} ms')
            + table('kEchoDark', 'i32', dark, f'The echo loop\'s low-pass, Q31: {ECHO_DARK_HZ[0]:g} Hz at the shortest time to {ECHO_DARK_HZ[1]:g} Hz at the longest')
            + table('kLfoStep', 'u32', lfo, f'LFO 1\'s phase step per 64-sample block, 2^32 a cycle: {LFO_HZ[0]:g}..{LFO_HZ[1]:g} Hz')
            + table('kSweep', 'i32', sweep, f'The phaser\'s allpass coefficient, Q31, its corner {SWEEP_HZ[0]:g}..{SWEEP_HZ[1]:g} Hz')
            + '// The five diode curves, types I..V, Q31 across an input of -1..1: each\n'
            + '// of their 128 segments\' first point, and its step to the next as fx.cpp\n'
            + '// interpolates it, (next >> 8) - (point >> 8).\n'
            + f'const opxy::i32 kDiode[{len(TYPES)}][{DIODE_POINTS - 1}][2] = {{\n'
            + ''.join('    {' + ', '.join(f'{{{c[i]}, {(c[i + 1] >> 8) - (c[i] >> 8)}}}' for i in range(DIODE_POINTS - 1)) + '},\n'
                      for c in curves)
            + '};\n'
            + '}\n')
    (ROOT / 'tables.h').write_text(text)
    print('wrote tables.h')


if __name__ == '__main__':
    main()
